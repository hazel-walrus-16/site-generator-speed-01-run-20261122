// A faster drop-in for makefun-site 1.0.0: run(input) returns the same output tree build() returns for every
// input, byte for byte, with the hot paths rebuilt around it: single-pass Markdown with range-based inline
// parsing (no token objects, no substring slicing in the scanner), a fast-path HTML escaper that returns clean
// text untouched, a cached ASCII-fast-path slugifier, a whitespace-transition word counter, an index-scanning
// front-matter parser that never splits the body, and a template renderer that streams into a parts array.

'use strict';

// ------------------------------------------------------------ text: escape, slugs, dates, word counts

const ESC_AMP = '&amp;';
const ESC_LT = '&lt;';
const ESC_GT = '&gt;';
const ESC_QUOT = '&quot;';
const ESC_APOS = '&#39;';

const ESCAPES = { '&': ESC_AMP, '<': ESC_LT, '>': ESC_GT, '"': ESC_QUOT, "'": ESC_APOS };
const escReplacer = (c) => ESCAPES[c];

/** `s` with & < > " ' escaped; the common all-clean string is returned as itself. */
function escapeHtml(s) {
  return s.replace(/[&<>"']/g, escReplacer);
}

const SLUG_MAX = 64;
const slugCache = new Map();

/** The slug of `text`, cached: titles, headings and tag names repeat across a site. */
function slugify(text) {
  let out = slugCache.get(text);
  if (out === undefined) {
    out = slugifyRaw(text);
    slugCache.set(text, out);
  }
  return out;
}

function slugifyRaw(text) {
  // ASCII fast path: NFKD is the identity below U+0080 and no combining mark is ASCII, so the general
  // algorithm reduces to a charCode loop. The output is append-only, so once it reaches the cap its first
  // SLUG_MAX characters are final and the scan can stop.
  let ascii = true;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) >= 128) { ascii = false; break; }
  }
  if (ascii) {
    let out = '';
    let gap = false;
    for (let i = 0; i < text.length; i++) {
      const c = text.charCodeAt(i);
      let keep = -1;
      if (c >= 65 && c <= 90) keep = c + 32;
      else if ((c >= 97 && c <= 122) || (c >= 48 && c <= 57)) keep = c;
      if (keep === -1) {
        gap = out.length > 0;
        continue;
      }
      if (gap) {
        out += '-';
        gap = false;
        if (out.length >= SLUG_MAX) break;
      }
      out += String.fromCharCode(keep);
      if (out.length >= SLUG_MAX) break;
    }
    if (out.length > SLUG_MAX) out = out.slice(0, SLUG_MAX);
    while (out.endsWith('-')) out = out.slice(0, -1);
    return out === '' ? 'untitled' : out;
  }
  const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
  let out = '';
  let gap = false;
  for (const ch of plain) {
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  return out === '' ? 'untitled' : out;
}

/** `slug` made unique against `taken` (and added to it): the first of slug, slug-2, slug-3 ... not taken. */
function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** A YYYY-MM-DD date in words, from the string alone. */
function longDate(date) {
  return `${Number(date.slice(8, 10))} ${MONTHS[Number(date.slice(5, 7)) - 1]} ${date.slice(0, 4)}`;
}

/** Whether a char code is JavaScript's \s (the set a /\S+/ word run breaks on). */
function isWsCode(c) {
  if (c === 32 || (c >= 9 && c <= 13)) return true;
  if (c < 128) return false;
  return c === 0xa0 || c === 0x1680 || (c >= 0x2000 && c <= 0x200a) || c === 0x2028 || c === 0x2029 || c === 0x202f || c === 0x205f || c === 0x3000 || c === 0xfeff;
}

/** The words of a body: its runs of characters other than whitespace, counted by transitions. */
function wordsOf(text) {
  let n = 0;
  let inWord = false;
  for (let i = 0; i < text.length; i++) {
    if (isWsCode(text.charCodeAt(i))) inWord = false;
    else if (!inWord) {
      inWord = true;
      n++;
    }
  }
  return n;
}

// ------------------------------------------------------------ front matter

const FM_KEYS = new Set(['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary']);

/** The days of month `m` (1-12) of year `y`, by the Gregorian rule. */
function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

function isDigitAt(s, i) {
  const c = s.charCodeAt(i);
  return c >= 48 && c <= 57;
}

/** A string value: "..." with \" and \\ its only escapes, or bare, the rest of the line (never opening on " or [). */
function stringOf(raw) {
  if (raw.startsWith('"')) {
    if (raw.length < 2 || !raw.endsWith('"')) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.startsWith('[')) return { error: 'a bare string opens on [' };
  return { value: raw };
}

/** One key's value, or why it is refused. */
function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      let ok = raw.length === 10 && raw[4] === '-' && raw[7] === '-';
      if (ok) {
        for (const i of [0, 1, 2, 3, 5, 6, 8, 9]) {
          if (!isDigitAt(raw, i)) { ok = false; break; }
        }
      }
      if (ok) {
        const y = Number(raw.slice(0, 4));
        const mo = Number(raw.slice(5, 7));
        const d = Number(raw.slice(8, 10));
        ok = y >= 1970 && y <= 2099 && mo >= 1 && mo <= 12 && d >= 1 && d <= daysIn(y, mo);
      }
      return ok ? { value: raw } : { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
    }
    case 'tags': {
      if (!raw.startsWith('[') || !raw.endsWith(']')) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      for (const t of tags) {
        if (t === '' || t.includes('"') || t.includes('[') || t.includes(']')) return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
      }
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout': {
      if (raw === '') return { error: 'key "layout": not a template name' };
      for (let i = 0; i < raw.length; i++) {
        const c = raw.charCodeAt(i);
        if (!((c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 45)) return { error: 'key "layout": not a template name' };
      }
      return { value: raw };
    }
    case 'slug': {
      // [a-z0-9]+(-[a-z0-9]+)* and at most 64 characters.
      let ok = raw.length >= 1 && raw.length <= 64;
      if (ok) {
        let seg = 0;
        for (let i = 0; i <= raw.length; i++) {
          if (i === raw.length || raw[i] === '-') {
            if (seg === 0) { ok = false; break; }
            seg = 0;
          } else {
            const c = raw.charCodeAt(i);
            if (!((c >= 97 && c <= 122) || (c >= 48 && c <= 57))) { ok = false; break; }
            seg++;
          }
        }
      }
      return ok ? { value: raw } : { error: 'key "slug": not a slug' };
    }
    default:
      return { error: `unknown key "${key}"` };
  }
}

/**
 * A source's front matter and body: { data, body }, or { error } with the first reason it is refused. Only the
 * front-matter lines are ever split out; the body is one slice of the source text.
 */
function parseFrontMatter(text) {
  const firstNl = text.indexOf('\n');
  const first = firstNl === -1 ? text : text.slice(0, firstNl);
  if (first !== '---') return { error: 'no front matter' };
  if (firstNl === -1) return { error: 'the front matter is not closed' };
  // Walk the lines after the opening --- (split index i starts at 1), collecting them until the closing ---.
  const fmLines = [];
  let closeBodyStart = -1;
  let pos = firstNl + 1;
  let i = 1;
  for (;;) {
    const nl = text.indexOf('\n', pos);
    const line = nl === -1 ? text.slice(pos) : text.slice(pos, nl);
    if (line === '---') {
      closeBodyStart = nl === -1 ? text.length : nl + 1;
      break;
    }
    fmLines.push({ line, num: i + 1 });
    if (nl === -1) break;
    pos = nl + 1;
    i++;
  }
  if (closeBodyStart === -1) return { error: 'the front matter is not closed' };
  const data = {};
  for (const { line, num } of fmLines) {
    if (isBlankLine(line) || line.startsWith('#')) continue;
    // "key: value": a key of a-z and _, a colon, then end of line or one space and the value.
    let k = 0;
    while (k < line.length) {
      const c = line.charCodeAt(k);
      if ((c >= 97 && c <= 122) || c === 95) k++;
      else break;
    }
    let raw;
    if (k === 0 || line[k] !== ':') return { error: `line ${num} is not "key: value"` };
    if (k + 1 === line.length) raw = '';
    else if (line[k + 1] === ' ') raw = line.slice(k + 2);
    else return { error: `line ${num} is not "key: value"` };
    const key = line.slice(0, k);
    raw = raw.replace(/[ \t]+$/, '');
    if (!FM_KEYS.has(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  return { data, body: text.slice(closeBodyStart) };
}

/** A line of nothing but spaces and tabs (the empty line included). */
function isBlankLine(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

// ------------------------------------------------------------ markdown

/** A line's trailing spaces and tabs dropped, and its leading ones: the rendered form of a text line. */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b) {
    const c = line.charCodeAt(a);
    if (c === 32 || c === 9) a++;
    else break;
  }
  while (b > a) {
    const c = line.charCodeAt(b - 1);
    if (c === 32 || c === 9) b--;
    else break;
  }
  return a === 0 && b === line.length ? line : line.slice(a, b);
}

/** Whether the rest of `line` from index `i` is nothing but spaces and tabs. */
function restIsBlank(line, i) {
  for (; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A fence opening's language, or null: three backticks, language characters, then spaces/tabs only. */
function fenceLang(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let i = 3;
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45) i++;
    else break;
  }
  return restIsBlank(line, i) ? line.slice(3, i) : null;
}

/** Whether `line` closes a fence: three backticks, then spaces/tabs only. */
function isFenceClose(line) {
  return line.charCodeAt(0) === 96 && line.charCodeAt(1) === 96 && line.charCodeAt(2) === 96 && restIsBlank(line, 3);
}

/** A heading line's level and text, or null (a heading's text is never empty). */
function headingOf(line) {
  let n = 0;
  while (n < line.length && line[n] === '#') n++;
  if (n === 0 || n > 6) return null;
  const c = line.charCodeAt(n);
  if (c !== 32 && c !== 9) return null;
  let i = n;
  while (i < line.length) {
    const cc = line.charCodeAt(i);
    if (cc === 32 || cc === 9) i++;
    else break;
  }
  let b = line.length;
  while (b > i) {
    const cc = line.charCodeAt(b - 1);
    if (cc === 32 || cc === 9) b--;
    else break;
  }
  if (b === i) return null;
  return { depth: n, text: line.slice(i, b) };
}

/** Whether `line` is a thematic break: --- or ***, then spaces/tabs only. */
function isHR(line) {
  const c = line.charCodeAt(0);
  if (c !== 45 && c !== 42) return false;
  return line.charCodeAt(1) === c && line.charCodeAt(2) === c && restIsBlank(line, 3);
}

/** A bullet item's text, or null: "- " or "* ". */
function bulletOf(line) {
  const c = line.charCodeAt(0);
  return (c === 45 || c === 42) && line.charCodeAt(1) === 32 ? line.slice(2) : null;
}

/** An ordered item's number and text, or null: 1-9 digits, ". ". */
function orderedOf(line) {
  let i = 0;
  while (i < line.length && i < 10) {
    const c = line.charCodeAt(i);
    if (c >= 48 && c <= 57) i++;
    else break;
  }
  if (i === 0 || i > 9) return null;
  if (line[i] !== '.' || line.charCodeAt(i + 1) !== 32) return null;
  return { num: Number(line.slice(0, i)), text: line.slice(i + 2) };
}

/** Whether `line` continues a list item: two or more spaces, then a non-whitespace character. */
function isContinued(line) {
  let i = 0;
  while (line.charCodeAt(i) === 32) i++;
  return i >= 2 && i < line.length && !isWsCode(line.charCodeAt(i));
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  return isBlankLine(line) || fenceLang(line) !== null || headingOf(line) !== null || isHR(line);
}

// The characters a backslash escapes, as a char-code table.
const ESCAPABLE = new Uint8Array(128);
for (const ch of '\\`*_[]()#+-.!>') ESCAPABLE[ch.charCodeAt(0)] = 1;

function isEscapable(c) {
  const code = c.charCodeAt(0);
  return code < 128 && ESCAPABLE[code] === 1;
}

/** The first index in s[from, end) where `what` stands outside a backslash escape, or -1. */
function findUnescaped(s, what, from, end) {
  const wlen = what.length;
  const w0 = what[0];
  for (let j = from; j <= end - wlen; j++) {
    if (s[j] === '\\' && j + 1 < end && isEscapable(s[j + 1])) {
      j++;
      continue;
    }
    if (s[j] === w0 && (wlen === 1 || s[j + 1] === what[1])) return j;
  }
  return -1;
}

/** The first single * in s[from, end) (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from, end) {
  for (let j = from; j < end; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < end && isEscapable(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (j + 1 < end && s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/**
 * s[a, b) rendered inline into `parts`; `env.link(target)` is a link's href. Plain runs are escaped a slice at
 * a time; the constructs recurse on ranges of the same string, so nothing is ever copied to find a closer.
 */
const INLINE_SCAN = /[\\`*[]/g;

function inlineRange(s, a, b, env, parts) {
  let runStart = a;
  let i = a;
  const flush = (upto) => {
    if (upto > runStart) parts.push(escapeHtml(s.slice(runStart, upto)));
  };
  while (i < b) {
    const c = s[i];
    if (c !== '\\' && c !== '`' && c !== '*' && c !== '[') {
      // Plain stretch: jump straight to the next construct opener (the run stays open).
      INLINE_SCAN.lastIndex = i;
      const m = INLINE_SCAN.exec(s);
      i = m === null || m.index >= b ? b : m.index;
      continue;
    }
    if (c === '\\' && i + 1 < b && isEscapable(s[i + 1])) {
      flush(i);
      const n = s[i + 1];
      parts.push(n === '>' ? ESC_GT : n);
      i += 2;
      runStart = i;
      continue;
    }
    if (c === '`') {
      const j = s.indexOf('`', i + 1);
      if (j !== -1 && j < b && j > i + 1) {
        flush(i);
        parts.push('<code>', escapeHtml(s.slice(i + 1, j)), '</code>');
        i = j + 1;
        runStart = i;
      } else i++;
      continue;
    }
    if (c === '*') {
      if (i + 1 < b && s[i + 1] === '*') {
        const j = findUnescaped(s, '**', i + 2, b);
        if (j > i + 2) {
          flush(i);
          parts.push('<strong>');
          inlineRange(s, i + 2, j, env, parts);
          parts.push('</strong>');
          i = j + 2;
          runStart = i;
        } else i += 2;
      } else {
        const j = findSingleStar(s, i + 1, b);
        if (j > i + 1) {
          flush(i);
          parts.push('<em>');
          inlineRange(s, i + 1, j, env, parts);
          parts.push('</em>');
          i = j + 1;
          runStart = i;
        } else i++;
      }
      continue;
    }
    if (c === '[') {
      const k = findUnescaped(s, ']', i + 1, b);
      const m = k !== -1 && k + 1 < b && s[k + 1] === '(' ? boundedIndexOf(s, ')', k + 2, b) : -1;
      const target = m === -1 ? '' : s.slice(k + 2, m);
      if (target !== '' && !/\s/.test(target)) {
        flush(i);
        parts.push('<a href="', escapeHtml(env.link(target)), '">');
        inlineRange(s, i + 1, k, env, parts);
        parts.push('</a>');
        i = m + 1;
        runStart = i;
      } else i++;
      continue;
    }
    i++;
  }
  flush(b);
}

/** indexOf bounded to s[from, end): the index of `ch`, or -1 when it stands at or past `end`. */
function boundedIndexOf(s, ch, from, end) {
  const j = s.indexOf(ch, from);
  return j !== -1 && j < end ? j : -1;
}

const INLINE_SPECIAL = /[\\`*[]/;

/** `s` rendered inline; text holding no construct opener is only escaped. */
function inline(s, env) {
  if (!INLINE_SPECIAL.test(s)) return escapeHtml(s);
  const parts = [];
  inlineRange(s, 0, s.length, env, parts);
  return parts.join('');
}

/**
 * `src` rendered in one pass over its lines: its HTML (a "\n" after every block), its table of contents (every
 * level 2 and 3 heading: level, id and its inline HTML) and its excerpt (the first paragraph's inline HTML).
 */
function renderMarkdown(src, env) {
  const lines = src.split('\n');
  const ids = new Set();
  const parts = [];
  const toc = [];
  let excerpt = null;
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (isBlankLine(line)) {
      i++;
      continue;
    }
    const lang = fenceLang(line);
    if (lang !== null) {
      i++;
      parts.push('<pre><code');
      if (lang !== '') parts.push(' class="language-', escapeHtml(lang), '"');
      parts.push('>');
      while (i < lines.length && !isFenceClose(lines[i])) {
        parts.push(escapeHtml(lines[i]), '\n');
        i++;
      }
      i++;
      parts.push('</code></pre>\n');
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      const html = inline(heading.text, env);
      parts.push(`<h${heading.depth} id="${id}">`, html, `</h${heading.depth}>\n`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (isHR(line)) {
      parts.push('<hr>\n');
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) {
      const body = [];
      while (i < lines.length && lines[i].charCodeAt(0) === 62) {
        const raw = lines[i];
        const stripped = raw.charCodeAt(1) === 32 ? raw.slice(2) : raw.slice(1);
        const t = trimLine(stripped);
        if (t !== '') body.push(t);
        i++;
      }
      if (body.length === 0) parts.push('<blockquote>\n</blockquote>\n');
      else parts.push('<blockquote>\n<p>', inline(body.join('\n'), env), '</p>\n</blockquote>\n');
      continue;
    }
    const bullet = bulletOf(line);
    const ordered = bullet === null ? orderedOf(line) : null;
    if (bullet !== null || ordered !== null) {
      const isOrdered = ordered !== null;
      const items = [];
      let cur = [trimLine(isOrdered ? ordered.text : bullet)];
      items.push(cur);
      i++;
      while (i < lines.length) {
        const l = lines[i];
        const m = isOrdered ? orderedOf(l) : bulletOf(l);
        if (m !== null) {
          cur = [trimLine(isOrdered ? m.text : m)];
          items.push(cur);
          i++;
        } else if (isContinued(l)) {
          cur.push(trimLine(l));
          i++;
        } else break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      if (isOrdered && ordered.num !== 1) parts.push(`<ol start="${ordered.num}">\n`);
      else parts.push(`<${tag}>\n`);
      for (const item of items) parts.push('<li>', inline(item.join('\n'), env), '</li>\n');
      parts.push(`</${tag}>\n`);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < lines.length && !endsParagraph(lines[i])) {
      body.push(trimLine(lines[i]));
      i++;
    }
    const html = inline(body.join('\n'), env);
    if (excerpt === null) excerpt = html;
    parts.push('<p>', html, '</p>\n');
  }
  return { html: parts.join(''), toc, excerpt: excerpt ?? '' };
}

